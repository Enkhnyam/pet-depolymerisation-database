def body(text: str) -> str:
    """The manuscript without its preamble or its comments. Captions included.

    LaTeX thin spaces are folded into commas first. This check reads a macro's value as the
    macro file writes it -- "2,777" -- and looked for that string in the body, so "2\\,777",
    which is how a typesetter groups digits, matched nothing. \\CorpusCandidates and
    \\CorpusFiltered sat typed out in the funnel table through every run of this check.
    """
    start = text.find("\\begin{document}")
    text = text[start:] if start >= 0 else text
    text = re.sub(r"(\d)\\[,.]\s*(\d)", r"\1,\2", text)
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("%"))


def informative(value: str) -> bool:
    """Whether a macro's value is specific enough that seeing it typed out means something."""
    bare = value.replace(",", "").replace("\\%", "").strip()
    if not re.fullmatch(r"\d+(\.\d+)?", bare):
        return False                                    # p-values, ranges, anything with markup
    return float(bare) >= 10 or "." in bare


def hits(text: str, value: str) -> list[str]:
    """Each place `value` appears as a bare number rather than through a macro.

    Both groupings are searched: the macro file writes "2,777" and a manuscript may type it
    without the separator.
    """
    forms = {value, value.replace(",", "")}
    pattern = re.compile("|".join(rf"(?<![\d.\\]){re.escape(f)}(?![\d.])"
                                  for f in sorted(forms, key=len, reverse=True)))
    found = []
    for match in pattern.finditer(text):
        tail = text[match.end():match.end() + 14]
        if UNIT.match(tail.lstrip()):
            continue                                    # 15pt, 0.5\textfloatsep: typography
        context = text[max(0, match.start() - 60):match.end() + 45]
        if TYPOGRAPHY.search(context):
            continue                                    # a font-size declaration, not a claim
        found.append(" ".join(context.split()))
    return found


def undefined(text: str, defined) -> list[str]:
    """Macros the body uses that the macro file does not define.

    This is the direction that actually breaks a manuscript, and it was the direction nobody
    checked. The body cited \\AdjWithinRho and \\AdjWithinPositive for two revisions after the
    check that computes them renamed both to WithinPaper*; LaTeX prints "Undefined control
    sequence" into a log nobody reads and carries on.
    """
    return sorted({name for name in USE.findall(text)
                   if name not in defined and name not in LATEX})


def compute() -> dict:
    sources = [MACROS, ARTIFACTS / "paper_table_fields.tex", ARTIFACTS / "paper_table_matrix.tex"]
    text = "\n".join(p.read_text(encoding="utf-8") for p in sources if p.exists())
    defined = dict(DEFINITION.findall(text))
    exists = set(DEFINED.findall(text))
    broken = {}
    findings, excused = [], []
    for paper in PAPERS:
        path = ROOT / paper
        if not path.exists():
            continue
        text = body(path.read_text(encoding="utf-8"))
        missing = undefined(text, exists)
        if missing:
            broken[paper] = missing
        for name, value in sorted(defined.items()):
            if not informative(value):
                continue
            for context in hits(text, value):
                row = {"paper": paper, "macro": f"\\{name}", "value": value, "context": context}
                (excused if (name, value) in REVIEWED else findings).append(row)
    return {"defined": defined, "exists": exists, "findings": findings, "excused": excused,
            "broken": broken}


def main() -> None:
    sources(macros=MACROS)
    result = compute()
    print(f"\n{len(result['defined'])} macros defined, body text of {len(PAPERS)} manuscripts "
          f"scanned")
    print(f"  {len(result['excused'])} known coincidence(s) excused by name in REVIEWED")

    untraceable = provenance.compute()["unattributed"]
    if untraceable:
        print(f"\n  {len(untraceable)} macro(s) no check can be traced for:")
        for name in untraceable:
            print(f"    \\{name}")
        print("\n  each is a number the manuscript may quote whose provenance is unproven.")
        raise SystemExit(1)
    print(f"  all {len(result['defined'])} macros trace back to a check and a bundle")

    if result["broken"]:
        for paper, names in result["broken"].items():
            print(f"\n  {paper} uses macros nothing defines:")
            for name in names:
                print(f"    \\{name}")
        print("\n  each of these prints \"Undefined control sequence\" and builds anyway.")
        raise SystemExit(1)
    print("  every macro the body uses is defined")

    findings = result["findings"]
    if not findings:
        print("\nno literal in either body duplicates a computed value")
        return

    frame = pd.DataFrame(findings)
    show("values typed out that a macro already defines",
         frame.groupby(["paper", "macro", "value"]).size().rename("times"), fmt="{:.0f}")
    print()
    for row in findings:
        print(f"  {row['paper']}  {row['macro']}")
        print(f"    …{row['context']}…")
    print("\n  each of these is a number that will not move when the checks move.")
    print("  replace the literal with the macro, or add it to REVIEWED with its reason.")
    raise SystemExit(1)


if __name__ == "__main__":
    main()
