DEFINITION = re.compile(r"\\newcommand\{\\(\w+)\}\{(.+?)\}(?:\s*%.*)?$", re.M)
# Whether a macro exists at all is a different question from what its value is: \MatrixTableRows
# and \FieldTableRows hold whole table bodies over several lines, which DEFINITION cannot match
# and should not try to.
DEFINED = re.compile(r"\\newcommand\{\\(\w+)\}")
USE = re.compile(r"\\([A-Z][A-Za-z]*)")

# LaTeX's own capitalised control sequences, which appear in the body and are not ours. Short
# list on purpose: anything else matching \Capitalised is a paper macro, and if it is not
# defined the manuscript is quoting a number that no longer exists.
LATEX = {"Large", "LARGE", "Huge", "HUGE", "Roman", "Alph", "AA", "LaTeX", "TeX", "S",
         "IfFileExists"}
UNIT = re.compile(r"(pt|in|em|ex|cm|mm|\\textfloatsep|\\textwidth|\\columnwidth|\\linewidth)")
# \@setfontsize{12pt}{14} is typography, and the RSC template's block of them sits *after*
# \begin{document}, so body() cannot strip it as preamble. UNIT only looks forward, and the
# second argument of a setfontsize call is followed by a brace rather than a unit.
TYPOGRAPHY = re.compile(r"@setfontsize|\\the\\|setlength")

